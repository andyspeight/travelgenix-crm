/** Helper to render an icon by string id (used by the segmentation tokens). */
export function iconById(
  id: "plane" | "clock" | "users" | "sparkles" | "home",
  props?: IconProps
) {
  const map = {
    plane: PlaneIcon,
    clock: ClockIcon,
    users: UsersIcon,
    sparkles: SparklesIcon,
    home: HomeIcon,
  };
  const C = map[id];
  return <C {...props} />;
}
